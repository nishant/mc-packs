import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "node:test";
import { zip } from "../../lib/zip.mjs";
import { bundleMembers, installBehaviorPack, installResourcePack, loadBundle } from "./packs.mjs";
import { extractZip, readZip } from "./unzip.mjs";

const harnessDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function fixture(t, name) {
  const cache = path.join(harnessDir, ".cache");
  fs.mkdirSync(cache, { recursive: true });
  const dir = fs.mkdtempSync(path.join(cache, name));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return dir;
}

const manifest = (extra = {}) => JSON.stringify({
  format_version: 2,
  header: { name: "Realm Bundle", description: "Bundle of: A, B", uuid: "00000000-0000-4000-8000-000000000001", version: [2026, 1019, 700], min_engine_version: [1, 21, 100] },
  modules: [{ type: "script", language: "javascript", uuid: "00000000-0000-4000-8000-000000000002", version: [1, 0, 0], entry: "scripts/main.js" }],
  dependencies: [{ module_name: "@minecraft/server", version: "2.1.0" }, { module_name: "@minecraft/server-ui", version: "2.0.0" }],
  ...extra,
}, null, 2);
const file = (name, text) => ({ name, data: Buffer.from(text) });
const bundleFiles = (main = 'import "./a_bp/main.js";\nimport "./b_bp/main.js";\n') => [
  file("manifest.json", manifest()), file("scripts/main.js", `// Generated by tools/bundle.mjs - do not edit.\n${main}`),
  file("scripts/a_bp/main.js", "export const a = 1;\n"), file("scripts/b_bp/main.js", "export const b = 2;\n"), file("texts/en_US.lang", "a=1\nb=2\n"),
];

test("reads back what tools/lib/zip.mjs writes and refuses unsafe or corrupt archives", () => {
  const entries = readZip(zip(bundleFiles()));
  assert.deepEqual(entries.map((e) => e.name), ["manifest.json", "scripts/main.js", "scripts/a_bp/main.js", "scripts/b_bp/main.js", "texts/en_US.lang"]);
  assert.equal(entries.at(-1).data.toString(), "a=1\nb=2\n");
  assert.throws(() => readZip(zip([file("../evil.txt", "x")])), /unsafe path/);
  assert.throws(() => readZip(Buffer.from("not a zip at all, long enough to be scanned for a directory record")), /not a zip file/);
  const damaged = Buffer.from(zip([file("a.txt", "hello hello hello")]));
  damaged[damaged.indexOf(Buffer.from("a.txt")) + 5] ^= 0xff; // flips the first byte of the compressed data
  assert.throws(() => readZip(damaged), /CRC|invalid|corrupt|unexpected/i);
});

test("loads a merged bundle as ONE pack with its members, and installs it under the shim as one script entry", (t) => {
  const dir = fixture(t, "bundle-");
  const mcpack = path.join(dir, "realm_bundle.mcpack");
  fs.writeFileSync(mcpack, zip(bundleFiles()));
  const pack = loadBundle(mcpack, path.join(dir, "work"));
  assert.equal(pack.kind, "bp");
  assert.equal(pack.folder, "realm_bundle");
  assert.deepEqual(pack.members, ["a_bp", "b_bp"]);
  assert.deepEqual(bundleMembers(pack.dir), ["a_bp", "b_bp"]);

  const server = path.join(dir, "server");
  fs.mkdirSync(path.join(server, "development_behavior_packs"), { recursive: true });
  const entry = installBehaviorPack(pack, server, { shim: true, profile: true, relay: true });
  assert.equal(entry.pack_id, "00000000-0000-4000-8000-000000000001");
  const installed = path.join(server, "development_behavior_packs", "realm_bundle");
  const installedManifest = JSON.parse(fs.readFileSync(path.join(installed, "manifest.json"), "utf8"));
  assert.equal(installedManifest.modules.filter((m) => m.type === "script").length, 1, "one script module");
  assert.equal(installedManifest.modules[0].entry, "scripts/__harness_entry.js");
  assert.ok(installedManifest.dependencies.some((d) => d.module_name === "@minecraft/server-gametest"));
  const wrapper = fs.readFileSync(path.join(installed, "scripts", "__harness_entry.js"), "utf8");
  assert.match(wrapper, /import "\.\/__harness_shim\.js";[\s\S]*import "\.\/__harness_profile\.js";[\s\S]*import "\.\/main\.js";/);
  assert.match(fs.readFileSync(path.join(installed, "scripts", "__harness_shim.js"), "utf8"), /const PACK = "realm_bundle";/);
  for (const member of ["a_bp", "b_bp"]) assert.ok(fs.existsSync(path.join(installed, "scripts", member, "main.js")));
  assert.deepEqual(fs.readFileSync(path.join(installed, "scripts", "main.js"), "utf8").match(/^import .*$/gm), ['import "./a_bp/main.js";', 'import "./b_bp/main.js";']);
});

test("rejects a behavior bundle that is not one merged script context", (t) => {
  const dir = fixture(t, "badbundle-");
  const one = path.join(dir, "one.mcpack");
  fs.writeFileSync(one, zip(bundleFiles('import "./a_bp/main.js";\n')));
  assert.throws(() => loadBundle(one, path.join(dir, "work")), /imports 1 pack\(s\): that is not a merged bundle/);
  const two = path.join(dir, "two.mcpack");
  const twoScripts = JSON.parse(manifest());
  twoScripts.modules.push({ type: "script", language: "javascript", uuid: "00000000-0000-4000-8000-000000000003", version: [1, 0, 0], entry: "scripts/other.js" });
  fs.writeFileSync(two, zip([file("manifest.json", JSON.stringify(twoScripts)), ...bundleFiles().slice(1)]));
  assert.throws(() => loadBundle(two, path.join(dir, "work")), /exactly one script module \(found 2\)/);
  assert.throws(() => loadBundle(path.join(dir, "missing.mcpack"), dir), /no such bundle: .*node tools\/bundle\.mjs --all/);
});

test("loads a resource bundle and an unpacked bundle folder", (t) => {
  const dir = fixture(t, "rpbundle-");
  const rpManifest = JSON.parse(manifest());
  rpManifest.header.name = "Realm Resources";
  rpManifest.modules = [{ type: "resources", uuid: "00000000-0000-4000-8000-000000000009", version: [1, 0, 0] }];
  rpManifest.dependencies = [];
  const rp = path.join(dir, "realm_resources.mcpack");
  fs.writeFileSync(rp, zip([file("manifest.json", JSON.stringify(rpManifest)), file("textures/x.json", "{}")]));
  const pack = loadBundle(rp, path.join(dir, "work"));
  assert.equal(pack.kind, "rp");
  assert.deepEqual(pack.members, []);
  const server = path.join(dir, "server");
  fs.mkdirSync(path.join(server, "development_resource_packs"), { recursive: true });
  installResourcePack(pack, server);
  assert.ok(fs.existsSync(path.join(server, "development_resource_packs", "realm_resources", "textures", "x.json")));

  const unpacked = path.join(dir, "unpacked_bundle");
  extractZip(path.join(dir, "realm_resources.mcpack"), unpacked);
  assert.equal(loadBundle(unpacked, dir).folder, "unpacked_bundle");
});
