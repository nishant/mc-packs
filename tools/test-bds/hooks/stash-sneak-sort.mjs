// Test hook for tools/test-bds/examples/stash-sneak-sort.js: a two-pack mini bundle (claims_bp, then stash_bp, the order of the
// Realm Bundle) built the way tools/bundle.mjs merges behavior packs: each pack's scripts under scripts/<folder>/, one generated
// scripts/main.js importing them, every other pack folder (entities, items) merged at the top, so both share one script context and
// one dynamic property store.
//
// A simulated player's empty-hand tap fires no playerInteractWithBlock event, so the bundle also carries a tap relay (tap_hook.js,
// imported first). It remembers every playerInteractWithBlock before-listener in the order the packs registered them, and on the
// script event `harness:tap` { id, player, x, y, z, hand: "empty" | "pickaxe", reverse? } hands one real event object to all of them,
// the way the engine does inside one add-on: the same object, a listener after a cancel still runs. `reverse: true` runs the
// listeners in the opposite order, which is a Land Claims that loads after Quick Stack & Sort. It answers `harness:tap_result`
// { id, cancel, error? } once every listener has run (what they defer to the next tick is still to come).
//   node tools/test-bds/hooks/stash-sneak-sort.mjs <out dir>
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "..", "..");
const [out] = process.argv.slice(2);
if (!out) throw new Error("usage: stash-sneak-sort.mjs <out dir>");
const dest = join(out, "stash_sneak_bp");
rmSync(dest, { recursive: true, force: true });
mkdirSync(join(dest, "scripts"), { recursive: true });

const folders = ["claims_bp", "stash_bp"];
for (const folder of folders) {
  const pack = join(root, "packs", folder);
  for (const entry of readdirSync(pack)) {
    if (entry === "manifest.json") continue;
    cpSync(join(pack, entry), entry === "scripts" ? join(dest, "scripts", folder) : join(dest, entry), { recursive: true });
  }
}

writeFileSync(
  join(dest, "scripts", "tap_hook.js"),
  `import { Direction, ItemStack, system, world } from "@minecraft/server";

const taps = [];
const signal = world.beforeEvents.playerInteractWithBlock;
const subscribe = signal.subscribe.bind(signal);
signal.subscribe = (callback, ...rest) => {
  taps.push(callback);
  return subscribe(callback, ...rest);
};

system.afterEvents.scriptEventReceive.subscribe(
  ({ id, message }) => {
    if (id !== "harness:tap") return;
    const q = JSON.parse(message);
    let cancel = false;
    let error;
    try {
      const player = world.getAllPlayers().find((p) => p.name === q.player);
      const block = player.dimension.getBlock({ x: q.x, y: q.y, z: q.z });
      const event = {
        player,
        block,
        itemStack: q.hand === "pickaxe" ? new ItemStack("minecraft:wooden_pickaxe", 1) : undefined,
        blockFace: Direction.Up,
        isFirstEvent: true,
        cancel: false,
      };
      for (const listener of q.reverse ? [...taps].reverse() : taps) {
        try {
          listener(event);
        } catch (e) {
          error = String(e);
        }
      }
      cancel = event.cancel;
    } catch (e) {
      error = String(e);
    }
    system.sendScriptEvent("harness:tap_result", JSON.stringify({ id: q.id, cancel, error, listeners: taps.length }));
  },
  { namespaces: ["harness"] }
);
`
);

writeFileSync(join(dest, "scripts", "main.js"), `// Generated by tools/test-bds/hooks/stash-sneak-sort.mjs\nimport "./tap_hook.js";\n${folders.map((f) => `import "./${f}/main.js";`).join("\n")}\n`);

const manifest = JSON.parse(readFileSync(join(root, "packs", "stash_bp", "manifest.json"), "utf8"));
manifest.header.name = "Stash Sneak Test Bundle";
manifest.header.description = "Test bundle for stash-sneak-sort.js";
manifest.header.uuid = "5b0f5d8e-7a3c-4c19-9d4e-2f6a81c3b7a1";
manifest.header.version = [1, 0, 0];
const uuids = ["5b0f5d8e-7a3c-4c19-9d4e-2f6a81c3b7a2", "5b0f5d8e-7a3c-4c19-9d4e-2f6a81c3b7a3"];
manifest.modules.forEach((m, i) => {
  m.uuid = uuids[i];
  m.version = [1, 0, 0];
});
writeFileSync(join(dest, "manifest.json"), JSON.stringify(manifest, null, 2));
console.log(`wrote ${dest} (${folders.join(", ")}, tap relay)`);
