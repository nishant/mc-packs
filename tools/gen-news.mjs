// Writes packs/news_bp/scripts/release.js from the newest entry of docs/NEWS.md, so the Realm News
// popup always shows what the latest bundle changed, with no typing in game. Realm News shows a new
// entry (a new id) once to everyone after the packs are updated.
//   node tools/gen-news.mjs           write release.js (and bump news_bp's patch version once)
//   node tools/gen-news.mjs --check   fail if release.js doesn't match docs/NEWS.md
// npm run bundle runs it first. docs/NEWS.md: entries start with "## <title>", newest first; the
// text under a heading is the body (plain ASCII, blank lines kept, "- " bullets fine).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const newsPath = join(root, "docs", "NEWS.md");
const outPath = join(root, "packs", "news_bp", "scripts", "release.js");
const manifestPath = join(root, "packs", "news_bp", "manifest.json");
const check = process.argv.includes("--check");

const md = readFileSync(newsPath, "utf8").replace(/\r\n/g, "\n");
const parts = md.split(/^## /m).slice(1);
if (!parts.length) throw new Error("docs/NEWS.md has no '## ' entry");
const [head, ...rest] = parts[0].split("\n");
const title = head.trim();
const body = rest
  .join("\n")
  .replace(/^---\s*$/m, "")
  .replace(/\*\*(.+?)\*\*/g, "$1")
  .replace(/`([^`]+)`/g, "$1")
  .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
  .replace(/^- /gm, "- ")
  .trim();
for (const [i, ch] of [...title + body].entries()) {
  const c = ch.codePointAt(0) ?? 0;
  if (c > 127 && ch !== "§") throw new Error(`docs/NEWS.md newest entry: "${ch}" at ${i} is not ASCII (game text must be plain ASCII)`);
}
const id = createHash("sha256").update(title + "\n" + body).digest("hex").slice(0, 12);
const src =
  `// Generated by tools/gen-news.mjs from the newest entry of docs/NEWS.md. Don't edit: change docs/NEWS.md.\n` +
  `export const RELEASE = ${JSON.stringify({ id, title, body }, null, 2)};\n`;

let current = "";
try {
  current = readFileSync(outPath, "utf8");
} catch {}
if (check) {
  if (current !== src) {
    console.error("news_bp/scripts/release.js is out of date with docs/NEWS.md (run node tools/gen-news.mjs)");
    process.exit(1);
  }
  console.log(`Realm News release matches docs/NEWS.md ("${title}").`);
} else if (current === src) {
  console.log(`news_bp/scripts/release.js is current ("${title}").`);
} else {
  writeFileSync(outPath, src);
  const raw = readFileSync(manifestPath, "utf8");
  const manifest = JSON.parse(raw);
  let committed;
  try {
    committed = JSON.parse(execFileSync("git", ["show", "HEAD:packs/news_bp/manifest.json"], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] })).header.version;
  } catch {
    committed = undefined;
  }
  const [x, y, z] = manifest.header.version;
  if (committed && committed.join(".") === manifest.header.version.join(".")) {
    // Any spacing inside the brackets (a hand bump may leave "[1,  7,  65]").
    const bumped = raw.replace(new RegExp(`"version": \\[\\s*${x},\\s*${y},\\s*${z}\\s*\\]`), `"version": [${x}, ${y}, ${z + 1}]`);
    if (bumped === raw) {
      console.error("couldn't find the header version in packs/news_bp/manifest.json to bump it: bump it by hand");
      process.exit(1);
    }
    writeFileSync(manifestPath, bumped);
    console.log(`wrote news_bp/scripts/release.js ("${title}"); news_bp is now ${x}.${y}.${z + 1}`);
  } else console.log(`wrote news_bp/scripts/release.js ("${title}")`);
}
